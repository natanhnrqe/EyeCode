package com.eyecode.language.ast;

/**
 * Kinds of AST nodes the parser can produce (Sprint 5.3a declarations,
 * Sprint 5.3b statements, Sprint 5.3c expressions, Sprint 5.3d control flow
 * extensions and switch expressions).
 * <p>
 * Only kinds that genuinely exist in the current declarative parser are
 * represented — no speculative kinds for future phases (semantic analysis,
 * type resolution, definite assignment).
 */
public enum AstNodeKind {

    COMPILATION_UNIT,
    PACKAGE_DECLARATION,
    IMPORT_DECLARATION,
    CLASS_DECLARATION,
    INTERFACE_DECLARATION,
    ENUM_DECLARATION,
    RECORD_DECLARATION,
    ANNOTATION,
    FIELD_DECLARATION,
    METHOD_DECLARATION,
    CONSTRUCTOR_DECLARATION,
    PARAMETER,
    TYPE,
    MODIFIER,

    BLOCK,
    EMPTY_STATEMENT,
    LOCAL_VARIABLE_DECLARATION,
    EXPRESSION_STATEMENT,
    IF_STATEMENT,
    CONDITION,
    THEN,
    ELSE,
    FOR_STATEMENT,
    INITIALIZER,
    UPDATE,
    ENHANCED_FOR_STATEMENT,
    VARIABLE,
    ITERABLE,
    WHILE_STATEMENT,
    DO_WHILE_STATEMENT,
    RETURN_STATEMENT,
    BREAK_STATEMENT,
    CONTINUE_STATEMENT,
    THROW_STATEMENT,
    TRY_STATEMENT,
    CATCH_CLAUSE,
    FINALLY_CLAUSE,
    SWITCH_STATEMENT,
    SWITCH_CASE,
    SWITCH_LABEL,
    SYNCHRONIZED_STATEMENT,
    LABELED_STATEMENT,
    DECLARATOR,
    SKIPPED,

    SWITCH_EXPRESSION,
    YIELD_STATEMENT,
    ASSERT_STATEMENT,
    TYPE_PATTERN,

    NAME_EXPRESSION,
    THIS_EXPRESSION,
    SUPER_EXPRESSION,
    LITERAL_EXPRESSION,
    UNARY_EXPRESSION,
    BINARY_EXPRESSION,
    ASSIGNMENT_EXPRESSION,
    TERNARY_EXPRESSION,
    INSTANCEOF_EXPRESSION,
    CAST_EXPRESSION,
    PARENTHESIZED_EXPRESSION,
    FIELD_ACCESS_EXPRESSION,
    METHOD_CALL_EXPRESSION,
    METHOD_REFERENCE_EXPRESSION,
    ARRAY_ACCESS_EXPRESSION,
    OBJECT_CREATION_EXPRESSION,
    ARRAY_CREATION_EXPRESSION,
    CLASS_LITERAL_EXPRESSION,
    LAMBDA_EXPRESSION,
    OPERATOR
}
